/*
    Operand : Value on which we want to do the operation.

    Operator : They do some operation on the operand.
        1. Arithmetic Operator.
        2. Assignment Operator.
        3. Relational Operator.
        4. Logical Operator.
        5. Bitwise Operator.
        6. Ternary Operator.
        7. Typeof Operator.
        8. Unary Operator.
*/

/* Arithmetic Operator */
/*
    +   Addition
    -   Subtraction
    *   Multiplication
    /   Division
    %   Reminder
    **  Exponentiation
*/

let num1 = 10;
let num2 = 3;

console.log(num1 + num2); //addition
console.log(num1 - num2); //subtraction
console.log(num1 * num2); //Multiplication
console.log(num1 / num2); //Division
console.log(num1 % num2); //Reminder
console.log(num1 ** num2); //Exponentiation

// Arithmetic Operator
console.log(10+2); //12  Addition
console.log(10-2); //8   Subtraction
console.log(10*2); //20  Multiplication
console.log(10/2); //5   Division
console.log(10%2); //0   Reminder

