/* a++ */
/*
    Step-1 : We first assign value of a that is old value.
    Step-2 : then increment by 1.
*/

let a = 10;
let y = a++;
console.log(a, y); // 11 10

/* a-- */
/*
    Step-1 : We first assign value of a that is old value.
    Step-2 : then decrement by 1.
*/

let b = 10;
let x = b--;
console.log(b, x); // 9 10


