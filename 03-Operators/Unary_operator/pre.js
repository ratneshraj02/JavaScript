/* ++a */
/*
    Step-1 : We first increment value of a  by 1.
    Step-2 : assign value of a to y.
*/

let a = 10;
let y = ++a;
console.log(a, y); // 11 11

/* --b */
/*
    Step-1 : We first decrement value of b  by 1.
    Step-2 : assign value of b to y.
*/

let b = 10;
let x = --b;
console.log(b, x); // 9 9
