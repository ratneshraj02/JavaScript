/* While Loop */
/*
    While loop checks your conditions again - again till the time it became false.
*/

console.log("Start the program");
let i = 1; //initializing a variable using which we will loop
while(i<=10) {  // checking the condition again-again till the time it became false.
    console.log(i);
    i+=1;  //updation
}
console.log("Ending the program");