/*
    How to store some value inside a program?
        To store values we can use variable, variable are memory buckets that store our and has a name as well.

    How to create Variables?
    There are three ways to create variable
        1.var - Deprecated
        2.let
        3.const
*/
//var <nameofvariable> = value
var marks = 90;
var score = 5;
console.log(marks);
console.log(score);

//let <nameofvariable> = value
let age = 19;
let flag = 0;
console.log(age);
console.log(flag);

//const <nameofvariable> =  value : This value can't we change any how.
const num = 12;
const num4 = 1234;
console.log(num);
console.log(num4);

/*
    Variable Naming Rules : 
            1. Variables can contain alphanumeric value, underscore and dollar sign.
            2. We cannot have space or any other Special character.
            3. We should give meaningful name so that reader can identify the names properly.
            4. Variables name cannot start with digit. it can have digit in between or at last.
            5. We cannot use keyword as name of variables.
*/
